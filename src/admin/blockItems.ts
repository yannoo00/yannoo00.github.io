export type BlockKey =
  | 'text'
  | 'h1'
  | 'h2'
  | 'h3'
  | 'quote'
  | 'divider'
  | 'bulletList'
  | 'orderedList'
  | 'taskList'
  | 'image'
  | 'code'
  | 'table'
  | 'diagram'

export interface BlockItem {
  key: BlockKey
  label: string
  icon: string
}

export interface BlockGroup {
  key: 'text' | 'list' | 'advanced'
  label: string
  items: BlockItem[]
}

